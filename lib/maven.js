/** Generate or update a Maven settings.xml with a China mirror and local repository. */

import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const MIRRORS = {
  aliyun: {
    label: 'Aliyun (Alibaba Cloud)',
    mirror: 'https://maven.aliyun.com/repository/public',
    repos: [
      'https://maven.aliyun.com/repository/public',
      'https://maven.aliyun.com/repository/central',
      'https://maven.aliyun.com/repository/spring',
      'https://maven.aliyun.com/repository/google',
    ],
  },
  tencent: {
    label: 'Tencent Cloud',
    mirror: 'https://mirrors.cloud.tencent.com/nexus/repository/maven-public/',
    repos: ['https://mirrors.cloud.tencent.com/nexus/repository/maven-public/'],
  },
  huawei: {
    label: 'Huawei Cloud',
    mirror: 'https://repo.huaweicloud.com/repository/maven/',
    repos: ['https://repo.huaweicloud.com/repository/maven/'],
  },
}

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

function buildSettings({ mirror, localRepo }) {
  const m = MIRRORS[mirror]
  const repoBlocks = (m?.repos || []).map((r) => `      <repository>
        <id>${mirror}-${m.repos.indexOf(r)}</id>
        <name>${esc(m.label)}</name>
        <url>${esc(r)}</url>
        <releases><enabled>true</enabled></releases>
        <snapshots><enabled>true</enabled></snapshots>
      </repository>`).join('\n')

  const mirrorBlock = m
    ? `    <mirror>
      <id>${mirror}</id>
      <name>${esc(m.label)}</name>
      <url>${esc(m.mirror)}</url>
      <mirrorOf>central</mirrorOf>
    </mirror>`
    : ''

  const profileBlock = m
    ? `    <profile>
      <id>env-manager-${mirror}</id>
      <repositories>
${repoBlocks}
      </repositories>
      <pluginRepositories>
${repoBlocks.replace(/<repository>/g, '<pluginRepository>').replace(/<\/repository>/g, '</pluginRepository>')}
      </pluginRepositories>
    </profile>
`
    : ''

  const activeBlock = m ? `    <activeProfile>env-manager-${mirror}</activeProfile>` : ''

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by env-manager (DSH plugin) -->
<settings xmlns="http://maven.apache.org/SETTINGS/1.0.0"
          xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
          xsi:schemaLocation="http://maven.apache.org/SETTINGS/1.0.0 https://maven.apache.org/xsd/settings-1.0.0.xsd">
  <localRepository>${esc(localRepo)}</localRepository>

  <mirrors>
${mirrorBlock}
  </mirrors>

  <profiles>
${profileBlock}  </profiles>

${activeBlock ? `  <activeProfiles>\n${activeBlock}\n  </activeProfiles>\n` : ''}</settings>
`
}

export function configureMaven(opts = {}) {
  const mirror = opts.mirror && opts.mirror !== 'none' ? opts.mirror : 'aliyun'
  const settingsPath = opts.settingsPath || path.join(os.homedir(), '.m2', 'settings.xml')
  const localRepo = opts.localRepo || path.join(os.homedir(), '.m2', 'repository')

  if (!MIRRORS[mirror] && mirror !== 'none') {
    throw new Error(`Unknown mirror '${mirror}'. Choose one of: ${Object.keys(MIRRORS).join(', ')}, none`)
  }

  const content = buildSettings({ mirror, localRepo })

  let backup = null
  if (fs.existsSync(settingsPath)) {
    if (opts.overwrite === false) {
      return {
        settingsPath,
        written: false,
        reason: 'settings.xml already exists; pass overwrite: true to replace it (a backup is kept).',
        existing: fs.readFileSync(settingsPath, 'utf8'),
      }
    }
    backup = `${settingsPath}.bak-${Date.now()}`
    fs.copyFileSync(settingsPath, backup)
  }

  fs.mkdirSync(path.dirname(settingsPath), { recursive: true })
  fs.writeFileSync(settingsPath, content, 'utf8')

  return {
    settingsPath,
    written: true,
    mirror: MIRRORS[mirror]?.label || 'none',
    localRepo,
    backup,
  }
}
